-- ===========================================================================
-- 0001_init.sql — KotaLabs CRM initial schema
-- Target: PostgreSQL 13+ (uses built-in gen_random_uuid()).
-- The migration runner executes each file inside a single transaction.
--
-- Conventions used across the whole database:
--   * Primary keys are UUIDs (so offline Android/device rows can be referenced).
--   * Human readable numbers (lead_number) are separate bigint identities.
--   * Status-like columns are `text` + CHECK constraints instead of native
--     enums, so adding a value later is a normal, cheap migration.
--   * All timestamps are `timestamptz` stored in UTC; the UI renders IST.
--   * Phone numbers are stored normalised to E.164 (e.g. +919876543210).
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- Shared helpers
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- users — admin + employees (and, later, read-only accounts if needed)
-- ---------------------------------------------------------------------------
CREATE TABLE users (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name          text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 120),
  email         text NOT NULL CHECK (email = lower(email)),
  phone         text,
  password_hash text NOT NULL,
  role          text NOT NULL DEFAULT 'EMPLOYEE' CHECK (role IN ('ADMIN', 'EMPLOYEE')),
  status        text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
  last_login_at timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT users_email_unique UNIQUE (email)
);

CREATE TRIGGER users_set_updated_at
  BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- auth_refresh_tokens — rotating, revocable refresh tokens (hashed at rest)
-- ---------------------------------------------------------------------------
CREATE TABLE auth_refresh_tokens (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id        uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash     text NOT NULL UNIQUE,
  expires_at     timestamptz NOT NULL,
  revoked_at     timestamptz,
  replaced_by_id uuid REFERENCES auth_refresh_tokens (id) ON DELETE SET NULL,
  user_agent     text,
  ip_address     inet,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX auth_refresh_tokens_user_idx ON auth_refresh_tokens (user_id, expires_at DESC);

-- ---------------------------------------------------------------------------
-- devices — one row per registered Android phone
-- Only the SHA-256 of the device token is stored; the token is shown once.
-- ---------------------------------------------------------------------------
CREATE TABLE devices (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id        uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  device_code    text NOT NULL CHECK (char_length(btrim(device_code)) BETWEEN 1 AND 60),
  device_name    text,
  manufacturer   text,
  model          text,
  android_version text,
  app_version    text,
  platform       text NOT NULL DEFAULT 'ANDROID' CHECK (platform IN ('ANDROID')),
  token_hash     text NOT NULL UNIQUE,
  status         text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'REVOKED')),
  revoked_at     timestamptz,
  revoked_reason text,
  last_seen_at   timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT devices_owner_code_unique UNIQUE (user_id, device_code)
);

CREATE INDEX devices_user_idx ON devices (user_id);
CREATE INDEX devices_status_idx ON devices (status);

CREATE TRIGGER devices_set_updated_at
  BEFORE UPDATE ON devices
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- leads — one row per customer enquiry (not per phone call)
-- ---------------------------------------------------------------------------
CREATE TABLE leads (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  lead_number      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  customer_name    text NOT NULL CHECK (char_length(btrim(customer_name)) BETWEEN 1 AND 160),
  phone            text NOT NULL CHECK (phone ~ '^\+[1-9][0-9]{6,14}$'),
  alternate_phone  text CHECK (alternate_phone IS NULL OR alternate_phone ~ '^\+[1-9][0-9]{6,14}$'),
  email            text,
  city             text,
  vehicle_type     text,
  vehicle_details  text,
  requirement      text,
  source           text NOT NULL DEFAULT 'MANUAL'
                     CHECK (source IN ('INSTAGRAM', 'YOUTUBE', 'GOOGLE_ADS', 'WHATSAPP',
                                       'PHONE_CALL', 'WALK_IN', 'REFERRAL', 'MANUAL', 'OTHER')),
  source_detail    text,
  platform_lead_id text,
  assigned_user_id uuid REFERENCES users (id) ON DELETE SET NULL,
  status           text NOT NULL DEFAULT 'NEW'
                     CHECK (status IN ('NEW', 'CONTACTED', 'INTERESTED', 'FOLLOW_UP',
                                       'CONVERTED', 'LOST')),
  notes            text,
  lost_reason      text,
  last_contacted_at timestamptz,
  next_followup_at timestamptz,
  closed_at        timestamptz,
  created_by       uuid REFERENCES users (id) ON DELETE SET NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT leads_lost_reason_required
    CHECK (status <> 'LOST' OR (lost_reason IS NOT NULL AND btrim(lost_reason) <> ''))
);

-- A platform lead ID must never be imported twice for the same source.
CREATE UNIQUE INDEX leads_source_platform_unique
  ON leads (source, platform_lead_id)
  WHERE platform_lead_id IS NOT NULL;

CREATE INDEX leads_phone_idx ON leads (phone);
-- Fast "is there an open lead for this number?" lookups during call matching.
CREATE INDEX leads_open_phone_idx ON leads (phone)
  WHERE status NOT IN ('CONVERTED', 'LOST');
CREATE INDEX leads_status_idx ON leads (status, created_at DESC);
CREATE INDEX leads_assigned_idx ON leads (assigned_user_id, status, created_at DESC);
CREATE INDEX leads_created_at_idx ON leads (created_at DESC);
CREATE INDEX leads_next_followup_idx ON leads (next_followup_at)
  WHERE next_followup_at IS NOT NULL;
-- Text search on name / phone / vehicle. Uses ILIKE; see docs for the pg_trgm
-- upgrade path once the table grows past a few hundred thousand rows.
CREATE INDEX leads_customer_name_idx ON leads (lower(customer_name) text_pattern_ops);

CREATE TRIGGER leads_set_updated_at
  BEFORE UPDATE ON leads
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- call_events — one row per individual call (SIM or manually logged WhatsApp)
-- event_id is generated by the Android app and is the idempotency key:
-- retries with the same event_id never create a second row.
-- ---------------------------------------------------------------------------
CREATE TABLE call_events (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id         uuid NOT NULL UNIQUE,
  lead_id          uuid REFERENCES leads (id) ON DELETE SET NULL,
  device_id        uuid REFERENCES devices (id) ON DELETE SET NULL,
  user_id          uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  phone_number     text NOT NULL CHECK (phone_number ~ '^\+[1-9][0-9]{6,14}$'),
  direction        text CHECK (direction IN ('INCOMING', 'OUTGOING', 'MISSED', 'REJECTED', 'UNKNOWN')),
  source           text NOT NULL DEFAULT 'SIM' CHECK (source IN ('SIM', 'WHATSAPP', 'MANUAL')),
  capture_method   text CHECK (capture_method IN ('CALL_LOG', 'CALL_SCREENING', 'MANUAL')),
  started_at       timestamptz NOT NULL,
  duration_seconds integer CHECK (duration_seconds IS NULL OR duration_seconds >= 0),
  sim_slot         smallint CHECK (sim_slot IS NULL OR sim_slot IN (1, 2)),
  notes            text,
  raw_payload      jsonb,
  created_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX call_events_phone_idx ON call_events (phone_number, started_at DESC);
CREATE INDEX call_events_user_idx ON call_events (user_id, started_at DESC);
CREATE INDEX call_events_lead_idx ON call_events (lead_id, started_at DESC);
CREATE INDEX call_events_unmatched_idx ON call_events (started_at DESC) WHERE lead_id IS NULL;
CREATE INDEX call_events_device_idx ON call_events (device_id, started_at DESC);

-- ---------------------------------------------------------------------------
-- lead_activities — append-only timeline of everything that happened on a lead
-- ---------------------------------------------------------------------------
CREATE TABLE lead_activities (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  lead_id    uuid NOT NULL REFERENCES leads (id) ON DELETE CASCADE,
  user_id    uuid REFERENCES users (id) ON DELETE SET NULL,
  type       text NOT NULL CHECK (type IN ('CREATED', 'NOTE', 'STATUS_CHANGE', 'ASSIGNMENT',
                                           'CALL', 'FOLLOWUP_SCHEDULED', 'FOLLOWUP_COMPLETED',
                                           'FOLLOWUP_CANCELLED', 'UPDATED', 'SOURCE_SYNC')),
  body       text,
  metadata   jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX lead_activities_lead_idx ON lead_activities (lead_id, created_at DESC);
CREATE INDEX lead_activities_user_idx ON lead_activities (user_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- followups — scheduled callbacks; leads.next_followup_at mirrors the earliest
-- pending follow-up so dashboards do not need an aggregate query.
-- ---------------------------------------------------------------------------
CREATE TABLE followups (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  lead_id          uuid NOT NULL REFERENCES leads (id) ON DELETE CASCADE,
  assigned_user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  due_at           timestamptz NOT NULL,
  status           text NOT NULL DEFAULT 'PENDING'
                     CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED', 'MISSED')),
  notes            text,
  completed_at     timestamptz,
  completed_by     uuid REFERENCES users (id) ON DELETE SET NULL,
  completion_notes text,
  created_by       uuid REFERENCES users (id) ON DELETE SET NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT followups_completed_consistency
    CHECK (status <> 'COMPLETED' OR completed_at IS NOT NULL)
);

CREATE INDEX followups_lead_idx ON followups (lead_id, due_at DESC);
CREATE INDEX followups_pending_idx ON followups (due_at) WHERE status = 'PENDING';
CREATE INDEX followups_assignee_idx ON followups (assigned_user_id, status, due_at);

CREATE TRIGGER followups_set_updated_at
  BEFORE UPDATE ON followups
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- webhook_events — raw, verified payloads from Meta / Google Ads (Stage 6)
-- Stored before processing so a failed import can be replayed and never lost.
-- ---------------------------------------------------------------------------
CREATE TABLE webhook_events (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  provider        text NOT NULL CHECK (provider IN ('META', 'GOOGLE_ADS')),
  idempotency_key text NOT NULL,
  event_type      text,
  signature_valid boolean NOT NULL DEFAULT false,
  status          text NOT NULL DEFAULT 'RECEIVED'
                    CHECK (status IN ('RECEIVED', 'PROCESSED', 'FAILED', 'DUPLICATE', 'IGNORED')),
  payload         jsonb NOT NULL,
  error           text,
  lead_id         uuid REFERENCES leads (id) ON DELETE SET NULL,
  received_at     timestamptz NOT NULL DEFAULT now(),
  processed_at    timestamptz,
  CONSTRAINT webhook_events_unique UNIQUE (provider, idempotency_key)
);

CREATE INDEX webhook_events_status_idx ON webhook_events (provider, status, received_at DESC);

-- ---------------------------------------------------------------------------
-- audit_logs — who did what (security requirement / incident review)
-- ---------------------------------------------------------------------------
CREATE TABLE audit_logs (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  actor_user_id  uuid REFERENCES users (id) ON DELETE SET NULL,
  actor_type     text NOT NULL DEFAULT 'USER'
                   CHECK (actor_type IN ('USER', 'DEVICE', 'SYSTEM', 'WEBHOOK')),
  action         text NOT NULL,
  entity_type    text,
  entity_id      text,
  ip_address     inet,
  user_agent     text,
  metadata       jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX audit_logs_created_idx ON audit_logs (created_at DESC);
CREATE INDEX audit_logs_entity_idx ON audit_logs (entity_type, entity_id, created_at DESC);
CREATE INDEX audit_logs_actor_idx ON audit_logs (actor_user_id, created_at DESC);
